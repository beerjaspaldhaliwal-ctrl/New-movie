def _ds_sample(z, extra=""):
    lp = _loop(z)
    loop = f' loopStart="{lp[0]}" loopEnd="{lp[1]}" loopEnabled="true"' if lp else ""
    return (f'      <sample path={quoteattr("../../" + z.file)} rootNote="{z.root}" loNote="{z.lo}" hiNote="{z.hi}"'
            f' loVel="{z.vlo}" hiVel="{z.vhi}"{loop}{extra}/>\n')


def _ds_doc(inst, title, groups_xml, attack, release, midi_xml="", info=""):
    cfg = inst.cfg
    fx = cfg.get("fx_defaults", {})
    tone = fx.get("tone", 1000) / 1000.0
    rev = fx.get("reverb", 250) / 1000.0
    knobs = [
        ("Attack", 0.0, 4.0, attack, '<binding type="amp" level="instrument" position="0" parameter="ENV_ATTACK"/>'),
        ("Release", 0.0, 8.0, release, '<binding type="amp" level="instrument" position="0" parameter="ENV_RELEASE"/>'),
        ("Tone", 0.0, 1.0, tone, '<binding type="effect" level="instrument" position="0" parameter="FX_FILTER_FREQUENCY"'
                                ' translation="table" translationTable="0,60;0.25,350;0.5,1500;0.75,6000;1,22000"/>'),
        ("Reverb", 0.0, 1.0, rev, '<binding type="effect" level="instrument" position="1" parameter="FX_REVERB_WET_LEVEL"/>'),
        ("Volume", 0.0, 1.0, 0.8, '<binding type="amp" level="instrument" position="0" parameter="AMP_VOLUME"'
                                 ' translation="linear" translationOutputMin="0" translationOutputMax="1"/>'),
    ]
    ui = []
    for i, (label, lo, hi, val, binding) in enumerate(knobs):
        ui.append(f'      <labeled-knob x="{40 + i * 150}" y="150" width="110" label="{label}" type="float" '
                  f'minValue="{lo}" maxValue="{hi}" value="{val:.3f}" textColor="FFE4E6EA" trackForegroundColor="FFDEB65C" '
                  f'trackBackgroundColor="FF383C48">\n        {binding}\n      </labeled-knob>')
    size = fx.get("rev_size", 600) / 1000.0
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- {LIB_NAME} - {title}. Generated by tools/nml/formats.py. Keep the library folder intact. -->
<DecentSampler minVersion="1.6.0">
  <ui width="812" height="375" bgColor="FF14161A" bgImage={quoteattr("../../Resources/pictures/NML Decent Sampler - " + inst.category.split(" ", 1)[1] + ".png")}>
    <tab name="main">
      <label x="40" y="30" width="700" height="40" text={quoteattr(title)} textColor="FFDEB65C" textSize="28"/>
      <label x="40" y="72" width="740" height="30" text={quoteattr(inst.blurb)} textColor="FF8A909E" textSize="14"/>
      <label x="40" y="300" width="740" height="30" text={quoteattr(info)} textColor="FF8A909E" textSize="13"/>
{chr(10).join(ui)}
    </tab>
  </ui>
  <groups attack="{attack:.3f}" decay="0" sustain="1" release="{release:.3f}">
{groups_xml}  </groups>
  <effects>
    <effect type="lowpass" frequency="{60 * (22000 / 60) ** tone:.0f}"/>
    <effect type="reverb" roomSize="{0.5 + 0.45 * size:.2f}" damping="0.4" wetLevel="{rev:.2f}"/>
  </effects>
{midi_xml}</DecentSampler>
"""


def dspreset_files(inst):
    cfg = inst.cfg
    groups = _by_group(inst)
    base = _clean(inst.name)
    att, rel = _env(inst)
    files = {}
    if inst.engine == "synth":
        layers = cfg.get("layers", inst.groups)
        vt = cfg.get("vsens", 50) / 100.0
        for g in layers:
            name = base if len(layers) == 1 else f"{base} - {g}"
            xml = f'    <group name={quoteattr(g)} ampVelTrack="{vt:.2f}">\n' + "".join(_ds_sample(z) for z in groups[g])
            xml += "    </group>\n"
            files[name + ".dspreset"] = _ds_doc(inst, f"{inst.name} - {g}" if len(layers) > 1 else inst.name, xml, att, rel,
                                                info=f"Range {note_name(cfg['range'][0])}-{note_name(cfg['range'][1])}")
    elif inst.engine == "artic":
        mics = cfg.get("mics", {})
        for a in cfg["arts"]:
            gs = a["groups"]
            xml, midi = "", ""
            if a["type"] == "short":
                n = len(gs)
                for k, g in enumerate(gs):
                    xml += (f'    <group name={quoteattr(g)} ampVelTrack="0.9" seqMode="round_robin" seqLength="{n}" '
                            f'seqPosition="{k + 1}" release="0.25">\n')
                    xml += "".join(_ds_sample(z) for z in groups[g]) + "    </group>\n"
                info = f"{len(gs)} round robins, velocity = loudness"
            else:
                a_att = 1.8 if a["type"] == "swell" else att
                gi = 0
                bindings = []
                for k, g in enumerate(gs):
                    for mic, grp in (("close", g), ("hall", mics.get(g))):
                        if not grp:
                            continue
                        vol = f' volume="{MIC_HALL_DB:.0f}dB"' if mic == "hall" else ""
                        xml += f'    <group name={quoteattr(grp)} ampVelTrack="0.3" attack="{a_att:.3f}"{vol}>\n'
                        xml += "".join(_ds_sample(z) for z in groups[grp]) + "    </group>\n"
                        if len(gs) == 2:  # mod wheel crossfades the soft and loud layers (equal power)
                            table = ("0,1;32,0.92;64,0.71;96,0.38;127,0" if k == 0 else "0,0;32,0.38;64,0.71;96,0.92;127,1")
                            bindings.append(f'      <binding type="amp" level="group" position="{gi}" parameter="AMP_VOLUME" '
                                            f'translation="table" translationTable="{table}"/>')
                        gi += 1
                if bindings:
                    midi = '  <midi>\n    <cc number="1">\n' + "\n".join(bindings) + "\n    </cc>\n  </midi>\n"
                info = "Mod wheel (CC1) = dynamics" if len(gs) == 2 else "Sustained articulation"
                if mics:
                    info += f", close + hall mics"
            files[f"{base} - {_clean(a['name'])}.dspreset"] = _ds_doc(inst, f"{inst.name} - {a['name']}", xml,
                                                                       1.8 if a["type"] == "swell" else att, rel, midi, info)
    elif inst.engine == "keys":
        patches = cfg["patches"]
        for p in patches:
            name = base if len(patches) == 1 else f"{base} - {_clean(p['name'])}"
            layers = p["layers"]
            xml = ""
            for (lo, hi), rrs in zip(_vel_ranges(p.get("splits", []), len(layers)), layers):
                for k, g in enumerate(rrs):
                    rr = (f' seqMode="round_robin" seqLength="{len(rrs)}" seqPosition="{k + 1}"' if len(rrs) > 1 else "")
                    xml += f'    <group name={quoteattr(g)} ampVelTrack="0.75"{rr}>\n'
                    for z in groups[g]:
                        xml += _ds_sample(z).replace(f'loVel="{z.vlo}" hiVel="{z.vhi}"', f'loVel="{lo}" hiVel="{hi}"')
                    xml += "    </group>\n"
            info = f"{len(layers)} velocity layer(s), {max(len(l) for l in layers)} round robin(s)"
            files[name + ".dspreset"] = _ds_doc(inst, f"{inst.name} - {p['name']}" if len(patches) > 1 else inst.name,
                                                xml, att, rel, info=info)
    else:
        pieces = cfg["pieces"]
        spread = cfg.get("spread", 70)
        by_key = {}
        for g, zs in groups.items():
            for z in zs:
                by_key[(g, z.lo)] = z
        xml = ""
        for p in pieces:
            cut, cg = p.get("cut", 0), p.get("cg", 0)
            tags = f' tags="choke{cut}"' if cut else ""
            silenced = f' silencedByTags="choke{cg}" silencingMode="fast"' if cg else ""
            pan = f' pan="{p.get("pan", 0.0) * spread:.0f}"' if p.get("pan") else ""
            hold_rel = rel if p.get("hold") else 4.0  # one-shots ring out after a short note
            layers = p["layers"]
            for (lo, hi), rrs in zip(_vel_ranges(p.get("splits", [127]), len(layers)), layers):
                n = len(rrs)
                rr = f' seqMode="random" seqLength="{n}"' if n > 1 else ""
                for k, g in enumerate(rrs):
                    z = by_key.get((g, p["key"]))
                    if z is None:
                        continue
                    pos = f' seqPosition="{k + 1}"' if n > 1 else ""
                    xml += (f'    <group name={quoteattr(p["name"])} ampVelTrack="0.85" release="{hold_rel:.2f}"'
                            f'{rr}{pos}{tags}{silenced}{pan}>\n')
                    s = _ds_sample(z) if p.get("hold") else _ds_sample(z).replace(' loopEnabled="true"', ' loopEnabled="false"')
                    xml += s.replace(f'loVel="{z.vlo}" hiVel="{z.vhi}"', f'loVel="{lo}" hiVel="{hi}"') + "    </group>\n"
        info = ", ".join(f"{note_name(p['key'])} {p['name']}" for p in pieces[:8]) + (" ..." if len(pieces) > 8 else "")
        files[base + ".dspreset"] = _ds_doc(inst, inst.name, xml, 0.0, rel, info=info)
    return files


def export(catalog, lib_dir):
    counts = {"SFZ": 0, "Decent Sampler": 0}
    for fmt, fn in (("SFZ", sfz_files), ("Decent Sampler", dspreset_files)):
        root = os.path.join(lib_dir, fmt)
        for inst in catalog:
            if inst.samples_from:  # presets of another instrument (Pulse Arp = Pluck Synth)
                continue
            for name, text in fn(inst).items():
                _write(os.path.join(root, inst.category, name), text)
                counts[fmt] += 1
    return counts
