"""Exports the library for free samplers: SFZ (sfizz, Sforzando, TAL-Sampler, ...)
and Decent Sampler (.dspreset).

These are simplified versions of the Kontakt instruments: the same samples,
mapping, velocity layers, round robins, loops, keyswitches (SFZ), dynamics
crossfades on the mod wheel, choke groups and envelopes, but without the
scripted Performer and the per-instrument effect chains.
"""
import os
from xml.sax.saxutils import quoteattr

from .library import LIB_NAME, note_name

DEFAULT_ATTACK = {"synth": 10, "artic": 0, "keys": 0, "drums": 0}
DEFAULT_RELEASE = {"synth": 600, "artic": 350, "keys": 250, "drums": 250}
MIC_HALL_DB = -6.0  # same default as the Kontakt / plugin Hall Mic fader


def _clean(name):
    return name.replace("/", "-").replace(":", "")


def _by_group(inst):
    out = {}
    for z in inst.zones:
        out.setdefault(z.group, []).append(z)
    return out


def _env(inst):
    cfg = inst.cfg
    return (cfg.get("attack", DEFAULT_ATTACK[inst.engine]) / 1000.0,
            cfg.get("release", DEFAULT_RELEASE[inst.engine]) / 1000.0)


def _vel_ranges(splits, n):
    """Velocity layers as the engines pick them: layer i plays while velocity <= splits[i]."""
    out, lo = [], 1
    for i in range(n):
        hi = splits[i] if i < len(splits) and i < n - 1 else 127
        out.append((lo, hi))
        lo = hi + 1
    return out


def _loop(z):
    if z.loop and z.loop[1] - z.loop[0] >= 16:
        return z.loop[0], z.loop[1] - 1  # inclusive loop end
    return None


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text)


# ===========================================================================
# SFZ
# ===========================================================================
def _sfz_region(z, extra=""):
    lp = _loop(z)
    loop = f" loop_mode=loop_continuous loop_start={lp[0]} loop_end={lp[1]}" if lp else ""
    return (f"<region> sample={z.file} pitch_keycenter={z.root} lokey={z.lo} hikey={z.hi}"
            f" lovel={z.vlo} hivel={z.vhi}{loop}{extra}\n")


def _sfz_header(inst, title, notes):
    att, rel = _env(inst)
    head = [f"// {LIB_NAME} - {title}", f"// {inst.blurb}"] + [f"// {n}" for n in notes]
    head += ["// Generated by tools/nml/formats.py. Samples: ../../Samples (keep the library folder intact).", "",
             "<control>", "default_path=../../", "set_cc1=90", "set_cc11=127", "",
             "<global>", f"ampeg_attack={att:.3f} ampeg_release={rel:.3f}", "amplitude_oncc11=100", ""]
    return "\n".join(head) + "\n"


def sfz_files(inst):
    """Returns {relative file name: text} for one instrument."""
    cfg = inst.cfg
    groups = _by_group(inst)
    files = {}
    base = _clean(inst.name)
    if inst.engine == "synth":
        layers = cfg.get("layers", inst.groups)
        vt = cfg.get("vsens", 50)
        for g in layers:
            name = base if len(layers) == 1 else f"{base} - {g}"
            text = _sfz_header(inst, f"{inst.name} ({g})", [f"Range {note_name(cfg['range'][0])}-{note_name(cfg['range'][1])}"])
            text += f"<group> amp_veltrack={vt}\n" + "".join(_sfz_region(z) for z in groups[g])
            files[name + ".sfz"] = text
        if len(layers) > 1 and cfg.get("layer_b", 0) > 0:  # the default two-layer blend
            import math
            b = cfg.get("blend", 350) / 1000.0
            ga, gb = layers[cfg.get("layer_a", 0)], layers[cfg["layer_b"] - 1]
            da = 20 * math.log10(max(math.cos(b * math.pi / 2), 1e-4))
            db = 20 * math.log10(max(math.sin(b * math.pi / 2), 1e-4))
            text = _sfz_header(inst, f"{inst.name} ({ga} + {gb})", ["The default blend of the two layers."])
            text += f"<group> amp_veltrack={vt} volume={da:.1f}\n" + "".join(_sfz_region(z) for z in groups[ga])
            text += f"<group> amp_veltrack={vt} volume={db:.1f}\n" + "".join(_sfz_region(z) for z in groups[gb])
            files[f"{base}.sfz"] = text
    elif inst.engine == "artic":
        arts = cfg["arts"]
        mics = cfg.get("mics", {})
        ks = [a["ks"] for a in arts]
        notes = ["Keyswitches: " + ", ".join(f"{note_name(a['ks'])} {a['name']}" for a in arts),
                 "Mod wheel (CC1) = dynamics of sustained articulations, CC11 = expression."]
        if mics:
            notes.append(f"Close + Hall microphones (Hall at {MIC_HALL_DB:.0f} dB).")
        text = _sfz_header(inst, inst.name, notes)
        text += f"<master> sw_lokey={min(ks)} sw_hikey={max(ks)} sw_default={ks[0]}\n"
        for a in arts:
            gs = a["groups"]
            sw = f" sw_last={a['ks']}"
            if a["type"] == "short":
                n = len(gs)
                for k, g in enumerate(gs):
                    text += f"<group>{sw} amp_veltrack=90 seq_length={n} seq_position={k + 1} ampeg_release=0.25\n"
                    text += "".join(_sfz_region(z) for z in groups[g])
                continue
            swell = " ampeg_attack=1.8" if a["type"] == "swell" else ""
            for k, g in enumerate(gs):
                if len(gs) == 2:
                    xf = " xfout_locc1=0 xfout_hicc1=127" if k == 0 else " xfin_locc1=0 xfin_hicc1=127"
                    xf += " xf_cccurve=power"
                else:
                    xf = " amplitude_oncc1=100"
                for mic, grp in (("close", g), ("hall", mics.get(g))):
                    if not grp:
                        continue
                    vol = f" volume={MIC_HALL_DB:.1f}" if mic == "hall" else ""
                    text += f"<group>{sw} amp_veltrack=30{xf}{swell}{vol}\n"
                    text += "".join(_sfz_region(z) for z in groups[grp])
        files[base + ".sfz"] = text
    elif inst.engine == "keys":
        patches = cfg["patches"]
        vt = 75 if cfg.get("vrange", 26) >= 20 else 50
        for p in patches:
            name = base if len(patches) == 1 else f"{base} - {_clean(p['name'])}"
            layers = p["layers"]
            text = _sfz_header(inst, f"{inst.name} - {p['name']}",
                               [f"{len(layers)} velocity layer(s), {max(len(l) for l in layers)} round robin(s)"])
            for (lo, hi), rrs in zip(_vel_ranges(p.get("splits", []), len(layers)), layers):
                for k, g in enumerate(rrs):
                    seq = f" seq_length={len(rrs)} seq_position={k + 1}" if len(rrs) > 1 else ""
                    text += f"<group> lovel={lo} hivel={hi} amp_veltrack={vt}{seq}\n"
                    text += "".join(_sfz_region(z, f"").replace(f" lovel={z.vlo} hivel={z.vhi}", "")
                                    for z in groups[g])
            files[name + ".sfz"] = text
    else:  # drums
        pieces = cfg["pieces"]
        spread = cfg.get("spread", 70)
        text = _sfz_header(inst, inst.name, ["Key map: " + ", ".join(f"{note_name(p['key'])} {p['name']}" for p in pieces)])
        by_key = {}
        for g, zs in groups.items():
            for z in zs:
                by_key[(g, z.lo)] = z
        for p in pieces:
            cut, cg = p.get("cut", 0), p.get("cg", 0)
            grp = f" group={1000 + cut}" if cut else (f" group={2000 + p['key']}" if cg else "")
            off = f" off_by={1000 + cg} off_mode=fast" if cg else ""
            mode = "" if p.get("hold") else " loop_mode=one_shot"
            pan = f" pan={p.get('pan', 0.0) * spread:.0f}" if p.get("pan") else ""
            layers = p["layers"]
            text += f"\n// {note_name(p['key'])} {p['name']}\n"
            for (lo, hi), rrs in zip(_vel_ranges(p.get("splits", [127]), len(layers)), layers):
                n = len(rrs)
                for k, g in enumerate(rrs):
                    z = by_key.get((g, p["key"]))
                    if z is None:
                        continue
                    rnd = f" lorand={k / n:.3f} hirand={(k + 1) / n:.3f}" if n > 1 else ""
                    lp = _loop(z) if p.get("hold") else None
                    loop = f" loop_mode=loop_continuous loop_start={lp[0]} loop_end={lp[1]}" if lp else ""
                    text += (f"<region> sample={z.file} key={p['key']} pitch_keycenter={z.root} lovel={lo} hivel={hi}"
                             f" amp_veltrack=85{rnd}{grp}{off}{mode}{pan}{loop}\n")
        files[base + ".sfz"] = text
    return files


