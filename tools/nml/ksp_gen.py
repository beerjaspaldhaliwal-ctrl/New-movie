def key_colors(s, ranges, ks=None, ks_active=None):
    """ranges: list of (lo, hi, color); ks: list of (note, name)."""
    lines = ["$kc_i := 0", "while ($kc_i < 128)", "set_key_color($kc_i, $KEY_COLOR_INACTIVE)",
             "set_key_type($kc_i, $NI_KEY_TYPE_NONE)", "set_key_name($kc_i, \"\")", "inc($kc_i)", "end while"]
    for lo, hi, color in ranges:
        lines += [f"$kc_i := {lo}", f"while ($kc_i <= {hi})", f"set_key_color($kc_i, {color})",
                  "set_key_type($kc_i, $NI_KEY_TYPE_DEFAULT)", "inc($kc_i)", "end while"]
    for note, name in (ks or []):
        lines += [f"set_key_color({note}, $KEY_COLOR_RED)", f"set_key_type({note}, $NI_KEY_TYPE_CONTROL)",
                  f"set_key_name({note}, {ksp_str(name)})"]
    if ks_active:
        lines += ks_active
    s.fn("color_keys", "\n".join(lines))
    s.persist.append("call color_keys")


