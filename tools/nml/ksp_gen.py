        "call build_chord",
        "if ($arp_mode > 0)",
        "$arp_lastvel := $p_vel",
        "$aa_src := $EVENT_NOTE",
        "call arp_add",
        "exit",
        "end if",
        "if (%src_n[$EVENT_NOTE] > 0)",
        "$rs_src := $EVENT_NOTE", "$rs_time := $retrig_us", "call release_src",
        "end if",
        "if ($hum_time > 0)",
        "wait(random(0, $hum_time * 1000) + 1)",
        "end if",
