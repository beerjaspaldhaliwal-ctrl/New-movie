def engine_artic(s):
    cfg = s.cfg
    groups = s.inst.groups
    arts = cfg["arts"]
    n = len(arts)
    lo, hi = cfg["range"]
    s.d(f"declare const $NUM_ART := {n}", f"declare !art_name[{n}]", f"declare %art_type[{n}]",
        f"declare %art_g[{n * 4}]", f"declare %art_gn[{n}]", f"declare %art_ks[{n}]", f"declare %rr_pos[{n}]",
        "declare $art", "declare $dyn := 90", "declare $dyn_gp", "declare $dyn_gf", "declare $dyn_db",
        "declare $expr_db", "declare $expr_cc := 127", "declare $vr_role", "declare $vr_base", "declare $vr_vol",
        "declare $ud_s", "declare $ud_i", "declare $ud_j", "declare $st_g", "declare $st_k", "declare $st_v",
        "declare $st_gi", "declare $st_gg", "declare $st_m", "declare $st_base", "declare $st_role",
        "declare $vr_m", "declare $vr_r", "declare %mic_db[2]", f"declare %hall_of[{len(groups)}] := (-1)",
        "declare %mono_v[32]", "declare %mono_r[32]", "declare %mono_b[32]", "declare $mono_n", "declare $mono_cur",
        "declare $mono_vel", "declare $gl_token", "declare $mt_i",
        "declare %stk[16]", "declare $stk_n", "declare $sk_i", "declare $sk_j", "declare $sk_note", "declare $ks_i",
        "declare polyphonic $p_i", "declare polyphonic $p_cnt", "declare polyphonic $p_vel",
        "declare polyphonic $p_tok", "declare polyphonic $p_from", "declare polyphonic $p_steps",
        "declare polyphonic $p_s", "declare polyphonic $q_tok", "declare polyphonic $q_from",
        "declare polyphonic $q_steps", "declare polyphonic $q_s", "declare polyphonic $q_tgt")
    type_code = {"sus": 0, "short": 1, "swell": 2}
    for i, a in enumerate(arts):
        s.d(f'!art_name[{i}] := "{a["name"]}"', f"%art_type[{i}] := {type_code[a['type']]}",
            f"%art_gn[{i}] := {len(a['groups'])}", f"%art_ks[{i}] := {a['ks']}")
        for k in range(4):
            gidx = groups.index(a["groups"][k]) if k < len(a["groups"]) else -1
            s.d(f"%art_g[{i * 4 + k}] := {gidx}")
    P = PAGE_PLAY
    s.label("lbl_art", P, 10, ROW1 - 2, "Articulation")
    s.ctl(Ctl("art_menu", "menu", P, 10, ROW1 + 16, items=[a["name"] for a in arts], default=0, width=140,
              help="Articulation. Keyswitches: " + ", ".join(f"{note_name(a['ks'])} {a['name']}" for a in arts),
              upd=["$art := $art_menu", "call color_keys"]))
    s.ctl(Ctl("dyn_knob", "knob", P, 160, ROW1, "Dynamics", 0, 127, 90, 1, None,
              help="Dynamics (mod wheel CC1). Crossfades soft and loud layers of sustained articulations.",
              upd=["$dyn := $dyn_knob", "call calc_dyn", "call update_dyn"]))
    s.label("lbl_dsrc", P, 258, ROW1 - 2, "Dyn Source")
    s.ctl(Ctl("dyn_src", "menu", P, 258, ROW1 + 16, items=["Mod Wheel", "Velocity"], default=0, width=96,
              help="Control sustain dynamics with the mod wheel (CC1) or with note velocity."))
    s.ctl(Ctl("dyn_range", "knob", P, 364, ROW1, "Dyn Range", 0, 40, cfg.get("dyn_range", 20), 1, "DB",
              help="Volume difference between softest and loudest dynamics.", upd=["call calc_dyn", "call update_dyn"]))
    env_controls(s, 462, ROW1, cfg.get("attack", 0), cfg.get("release", 350), 2000, 4000)
    s.ctl(Ctl("swell_t", "knob", P, 658, ROW1, "Swell Time", 100, 6000, 1800, 1, "MS",
              help="Fade-in time of the Swell articulation."))
    s.ctl(Ctl("legato", "switch", P, 10, ROW2 + 24, "Legato", default=cfg.get("legato", 0),
              help="Monophonic legato for sustained articulations: overlapping notes crossfade smoothly.",
              upd=["$rs_time := 30000", "call release_all", "$mono_n := 0", "$stk_n := 0"]))
    s.ctl(Ctl("leg_time", "knob", P, 108, ROW2, "Leg. Speed", 20, 400, 110, 1, "MS",
              help="Legato transition time."))
    s.ctl(Ctl("porta", "knob", P, 206, ROW2, "Portamento", 0, 100, 25, 1, "PERCENT",
              help="Amount of pitch slide into legato notes."))
    s.ctl(Ctl("vrange", "knob", P, 304, ROW2, "Vel Range", 0, 40, 22, 1, "DB",
              help="Velocity to volume range for short articulations."))
    s.ctl(Ctl("vcurve", "knob", P, 402, ROW2, "Vel Curve", -100, 100, 0, 1, None,
              help="Velocity curve: negative = softer response, positive = harder."))
    mics = cfg.get("mics", {})
    for close, hall in mics.items():
        s.d(f"%hall_of[{groups.index(close)}] := {groups.index(hall)}")
    if mics:
        s.ctl(Ctl("mic_close", "knob", P, 520, ROW2, "Close Mic", -400, 60, 0, 10, "DB",
                  help="Level of the close microphones (also used by the short articulations). Fully down = off.",
                  upd=["%mic_db[0] := $mic_close * 100", "if ($mic_close <= -400)", "%mic_db[0] := -100000", "end if",
                       "call update_dyn"]))
        s.ctl(Ctl("mic_hall", "knob", P, 618, ROW2, "Hall Mic", -400, 60, -60, 10, "DB",
                  help="Level of the distant hall microphones on sustained articulations. Fully down = off.",
                  upd=["%mic_db[1] := $mic_hall * 100", "if ($mic_hall <= -400)", "%mic_db[1] := -100000", "end if",
                       "call update_dyn"]))
    vel_db_fn(s)
    s.fn("calc_dyn", """
~fr := real($dyn) / 127.0
~fg := cos(~fr * 1.5707963)
if (~fg < 0.0001)
~fg := 0.0001
end if
$dyn_gp := int(20000.0 * log10(~fg))
~fg := sin(~fr * 1.5707963)
if (~fg < 0.0001)
~fg := 0.0001
end if
$dyn_gf := int(20000.0 * log10(~fg))
$dyn_db := 0 - int(real($dyn_range) * 1000.0 * pow(1.0 - ~fr, 1.3))
~fg := real($expr_cc) / 127.0
if (~fg < 0.001)
~fg := 0.001
end if
$expr_db := int(20000.0 * log10(~fg) * 0.9)
""")
    s.fn("voice_vol", """
$vr_m := $vr_role / 10
$vr_r := $vr_role mod 10
select ($vr_r)
case 0
$vr_vol := $dyn_gp + $dyn_db + $expr_db
case 1
$vr_vol := $dyn_gf + $dyn_db + $expr_db
case 2
$vr_vol := $dyn_db + $expr_db
case 3
$vr_vol := $vr_base + $expr_db
end select
$vr_vol := $vr_vol + %mic_db[$vr_m]
""")
    s.fn("update_dyn", """
$ud_s := 0
while ($ud_s < 128)
if (%src_n[$ud_s] > 0)
$ud_i := 0
while ($ud_i < %src_n[$ud_s])
$ud_j := $ud_s * $MAXV + $ud_i
$vr_role := %src_r[$ud_j]
$vr_base := %src_b[$ud_j]
call voice_vol
change_vol(%src_v[$ud_j], $vr_vol, 0)
inc($ud_i)
end while
end if
inc($ud_s)
end while
$ud_i := 0
while ($ud_i < $mono_n)
$vr_role := %mono_r[$ud_i]
$vr_base := %mono_b[$ud_i]
call voice_vol
change_vol(%mono_v[$ud_i], $vr_vol, 0)
inc($ud_i)
end while
""")
    mic_cond = "($st_m = 0 and $mic_close > -400) or ($st_m = 1 and $mic_hall > -400)" if mics else "$st_m = 0"
    s.fn("start_note", f"""
$nv_n := 0
$pv_note := $sn_note
$pv_tune := 0
$pv_pan := 0
$pv_off := $sn_off
$pv_fade := $att_us
if ($sn_fade >= 0)
$pv_fade := $sn_fade
end if
if (%art_type[$art] = 1)
$st_k := %rr_pos[$art]
%rr_pos[$art] := (%rr_pos[$art] + 1) mod %art_gn[$art]
$st_g := %grp[%art_g[$art * 4 + $st_k]]
if ($st_g # $NI_NOT_FOUND)
$vc_in := $sn_vel
call vel_curve
$st_base := $vc_db + random(-600, 600)
$vr_role := 3
$vr_base := $st_base
call voice_vol
$pv_grp := $st_g
$pv_role := 3
$pv_vol := $vr_vol
$pv_fade := 0
call play_voice
%nv_b[$nv_n - 1] := $st_base
end if
else
if (%art_type[$art] = 2)
$pv_fade := $swell_t * 1000
end if
$st_k := 0
while ($st_k < %art_gn[$art])
$st_gi := %art_g[$art * 4 + $st_k]
$st_g := %grp[$st_gi]
if ($st_g # $NI_NOT_FOUND)
if (%art_gn[$art] = 1)
$vr_role := 2
else
$vr_role := $st_k
end if
$st_base := 0
$st_role := $vr_role
if ($dyn_src = 1)
$st_v := $dyn
$dyn := $sn_vel
call calc_dyn
call voice_vol
$dyn := $st_v
call calc_dyn
$st_base := $vr_vol - $expr_db - %mic_db[0]
$st_role := 3
end if
$st_m := 0
while ($st_m < 2)
$st_gg := -1
if ($st_m = 0)
$st_gg := $st_g
else
if (%hall_of[$st_gi] >= 0)
$st_gg := %grp[%hall_of[$st_gi]]
end if
end if
if ($st_gg # -1 and $st_gg # $NI_NOT_FOUND and ({mic_cond}))
$pv_grp := $st_gg
$pv_role := $st_role + 10 * $st_m
$vr_role := $pv_role
$vr_base := $st_base
call voice_vol
$pv_vol := $vr_vol
call play_voice
%nv_b[$nv_n - 1] := $st_base
end if
inc($st_m)
end while
end if
inc($st_k)
end while
end if
""")
    s.fn("stack_remove", """
$sk_j := 0
$sk_i := 0
while ($sk_i < $stk_n)
if (%stk[$sk_i] # $sk_note)
%stk[$sk_j] := %stk[$sk_i]
inc($sk_j)
end if
inc($sk_i)
end while
$stk_n := $sk_j
""")
    s.fn("stack_push", """
call stack_remove
if ($stk_n < 16)
%stk[$stk_n] := $sk_note
inc($stk_n)
end if
""")
    s.fn("mono_take", """
$mt_i := 0
while ($mt_i < $nv_n)
%mono_v[$mt_i] := %nv_id[$mt_i]
%mono_r[$mt_i] := %nv_r[$mt_i]
%mono_b[$mt_i] := %nv_b[$mt_i]
inc($mt_i)
end while
$mono_n := $nv_n
""")
    s.fn("mono_fade_old", """
$mt_i := 0
while ($mt_i < $mono_n)
fade_out(%mono_v[$mt_i], $leg_time * 1000, 1)
inc($mt_i)
end while
""")

    def legato_block(pref, target, first_vel):
        return [
            "inc($gl_token)",
            f"${pref}tok := $gl_token",
            "if ($mono_n > 0)",
            f"${pref}from := ($mono_cur - {target}) * 1000 * $porta",
            "call mono_fade_old",
            f"$sn_note := {target}",
            "$sn_vel := $mono_vel",
            f"$sn_off := {cfg.get('leg_offset_us', 60000)}",
            "$sn_fade := $leg_time * 1000",
            "call start_note",
            "call mono_take",
            f"$mono_cur := {target}",
            f"if (${pref}from # 0)",
            f"${pref}steps := $leg_time / 5",
            f"if (${pref}steps < 1)", f"${pref}steps := 1", "end if",
            f"${pref}s := 0",
            f"while (${pref}s <= ${pref}steps and ${pref}tok = $gl_token)",
            "$mt_i := 0",
            "while ($mt_i < $mono_n)",
            f"change_tune(%mono_v[$mt_i], ${pref}from - (${pref}from / ${pref}steps) * ${pref}s + $bend, 0)",
            "inc($mt_i)",
            "end while",
            "wait(5000)",
            f"inc(${pref}s)",
            "end while",
            "end if",
            "else",
            f"$sn_note := {target}",
            f"$sn_vel := {first_vel}",
            "$sn_off := 0",
            "$sn_fade := -1",
            "call start_note",
            "call mono_take",
            f"$mono_cur := {target}",
            "end if",
        ]

    ks_lines = ["if (%art_ks[0] >= 0)", "$ks_i := 0", "while ($ks_i < $NUM_ART)",
                "if ($EVENT_NOTE = %art_ks[$ks_i])",
                "$art := $ks_i", "$art_menu := $ks_i", "call color_keys", "exit",
                "end if", "inc($ks_i)", "end while", "end if"]
    s.cb["note"] += note_head(s) + ks_lines + keys_down_track_note() + [
        "if ($legato = 1 and %art_type[$art] # 1)",
        "$mono_vel := $EVENT_VELOCITY",
        "$sk_note := $EVENT_NOTE",
        "call stack_push",
    ] + legato_block("p_", "$EVENT_NOTE", "$EVENT_VELOCITY") + ["exit", "end if"] + poly_note_path(s)
    ks_rel = ["$ks_i := 0", "while ($ks_i < $NUM_ART)", "if ($EVENT_NOTE = %art_ks[$ks_i])", "exit", "end if",
              "inc($ks_i)", "end while"]
    s.cb["release"] += ks_rel + keys_down_track_release() + [
        "if ($legato = 1 and $mono_n > 0)",
        "$sk_note := $EVENT_NOTE",
        "call stack_remove",
        "if ($EVENT_NOTE = $mono_cur)",
        "if ($stk_n > 0)",
        "$q_tgt := %stk[$stk_n - 1]",
    ] + legato_block("q_", "$q_tgt", "$mono_vel") + [
        "else",
        "$mt_i := 0",
        "while ($mt_i < $mono_n)", "fade_out(%mono_v[$mt_i], $rel_us, 1)", "inc($mt_i)", "end while",
        "$mono_n := 0",
        "inc($gl_token)",
        "end if",
        "end if",
        "exit",
        "end if",
    ] + poly_release_path(s)
    s.cb["controller"] += [
        "if ($CC_NUM = 1 and $dyn_src = 0)", "$dyn := %CC[1]", "$dyn_knob := %CC[1]",
        "call calc_dyn", "call update_dyn", "end if",
        "if ($CC_NUM = 11)", "$expr_cc := %CC[11]", "call calc_dyn", "call update_dyn", "end if",
    ]
