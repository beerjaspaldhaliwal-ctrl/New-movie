def common(s, melodic=True):
    inst, cfg = s.inst, s.cfg
    groups = inst.groups
    s.d('message("")', "make_perfview",
        f'set_script_title({ksp_str(LIB_NAME + " - " + inst.name)})',
        f"set_ui_width_px({W})", f"set_ui_height_px({H})",
        "set_listener($NI_SIGNAL_TIMER_BEAT, 24)",
        "{ ---- groups (looked up by name, so the order in the instrument does not matter) ---- }",
        f"declare const $NUM_GRP := {len(groups)}", f"declare %grp[{len(groups)}]",
        f"declare !grp_name[{len(groups)}]")
    for i, g in enumerate(groups):
        s.d(f'!grp_name[{i}] := "{g}"')
    s.d("declare $gi", "$gi := 0", "while ($gi < $NUM_GRP)",
        "%grp[$gi] := get_group_idx(!grp_name[$gi])",
        "if (%grp[$gi] = $NI_NOT_FOUND)",
        'message("NML: group not found: " & !grp_name[$gi] & " - rebuild with the Creator Tools script")',
        "end if", "inc($gi)", "end while",
        "{ ---- voice bookkeeping ---- }",
        "declare const $MAXV := 32",
        "declare %src_v[4128]", "declare %src_r[4128]", "declare %src_b[4128]",
        "declare %src_n[129]", "declare %src_held[129]", "declare %src_sus[129]",
        "declare %nv_id[32]", "declare %nv_r[32]", "declare %nv_b[32]", "declare $nv_n",
        "declare $pv_note", "declare $pv_grp", "declare $pv_vol", "declare $pv_tune", "declare $pv_off",
        "declare $pv_fade", "declare $pv_pan", "declare $pv_id", "declare $pv_role",
        "declare $rs_src", "declare $rs_time", "declare $rn_i", "declare $rn_j", "declare $rl_i",
        "declare $ra_s", "declare $ra_i", "declare $pu_s", "declare $pn_i", "declare $pp_i",
        "declare %pq_id[512]", "declare %pq_t[512]", "declare $pq_n", "declare $pq_rel",
        "declare $pedal", "declare $tick", "declare $bend", "declare $cb_v", "declare $keys_down",
        "declare $rel_us", "declare $att_us", "declare $retrig_us := 40000",
        "declare $page", "declare $ui_i", "declare $kc_i",
        "declare $fx_v", "declare ~fr", "declare ~fg",
        "declare $sn_note", "declare $sn_vel", "declare $sn_off", "declare $sn_fade")

    # UI chrome: tabs and info line
    s.ctl(Ctl("tab_play", "switch", ALWAYS, 8, 6, "PLAY", default=1, persist=False, width=86,
              in_presets=False, help="Main playing controls.", upd=["if ($tab_play = 1)", "$page := 0", "end if", "call show_page"]))
    s.ctl(Ctl("tab_sound", "switch", ALWAYS, 98, 6, "SOUND", default=0, persist=False, width=86,
              in_presets=False, help="Tone, width, chorus, delay and reverb.", upd=["if ($tab_sound = 1)", "$page := 1", "end if", "call show_page"]))
    if melodic:
        s.ctl(Ctl("tab_perf", "switch", ALWAYS, 188, 6, "PERFORM", default=0, persist=False, width=86,
                  in_presets=False, help="Scale lock, chords, strum, arpeggiator and humanise.",
                  upd=["if ($tab_perf = 1)", "$page := 2", "end if", "call show_page"]))
    s.label("info", ALWAYS, 284, 6, cfg.get("info", inst.name), 360)

    tabs = ["play", "sound"] + (["perf"] if melodic else [])
    lines = []
    for i, t in enumerate(tabs):
        lines.append(f"$tab_{t} := 0")
    for i, t in enumerate(tabs):
        lines += [f"if ($page = {i})", f"$tab_{t} := 1", "end if"]
    lines += ["$ui_i := 0", "while ($ui_i < $NUM_UI)",
              "if (%ui_page[$ui_i] = -1 or %ui_page[$ui_i] = $page)",
              "set_control_par(%ui_id[$ui_i], $CONTROL_PAR_HIDE, $HIDE_PART_NOTHING)",
              "else",
              "set_control_par(%ui_id[$ui_i], $CONTROL_PAR_HIDE, $HIDE_WHOLE_CONTROL)",
              "end if", "inc($ui_i)", "end while"]
    s.fn("show_page", "\n".join(lines))

    # voice functions
    s.fn("play_voice", """
$pv_id := play_note($pv_note, 127, $pv_off, 0)
set_event_par_arr($pv_id, $EVENT_PAR_ALLOW_GROUP, 0, $ALL_GROUPS)
set_event_par_arr($pv_id, $EVENT_PAR_ALLOW_GROUP, 1, $pv_grp)
change_vol($pv_id, $pv_vol, 0)
change_tune($pv_id, $pv_tune + $bend, 0)
if ($pv_pan # 0)
change_pan($pv_id, $pv_pan, 0)
end if
if ($pv_fade > 0)
fade_in($pv_id, $pv_fade)
end if
if ($nv_n < 32)
%nv_id[$nv_n] := $pv_id
%nv_r[$nv_n] := $pv_role
%nv_b[$nv_n] := $pv_vol
inc($nv_n)
end if
""")
    s.fn("reg_new", """
$rn_i := 0
while ($rn_i < $nv_n)
if (%src_n[$rs_src] < $MAXV)
$rn_j := $rs_src * $MAXV + %src_n[$rs_src]
%src_v[$rn_j] := %nv_id[$rn_i]
%src_r[$rn_j] := %nv_r[$rn_i]
%src_b[$rn_j] := %nv_b[$rn_i]
%src_n[$rs_src] := %src_n[$rs_src] + 1
else
fade_out(%nv_id[$rn_i], 30000, 1)
end if
inc($rn_i)
end while
""")
    s.fn("release_src", """
$rl_i := 0
while ($rl_i < %src_n[$rs_src])
fade_out(%src_v[$rs_src * $MAXV + $rl_i], $rs_time, 1)
inc($rl_i)
end while
%src_n[$rs_src] := 0
%src_sus[$rs_src] := 0
""")
    s.fn("pend_new", """
$pn_i := 0
while ($pn_i < $nv_n)
if ($pq_n < 512)
%pq_id[$pq_n] := %nv_id[$pn_i]
%pq_t[$pq_n] := $pq_rel
inc($pq_n)
else
fade_out(%nv_id[$pn_i], 20000, 1)
end if
inc($pn_i)
end while
""")
    s.fn("process_pending", """
$pp_i := 0
while ($pp_i < $pq_n)
if (%pq_t[$pp_i] <= $tick)
fade_out(%pq_id[$pp_i], $rel_us, 1)
dec($pq_n)
%pq_id[$pp_i] := %pq_id[$pq_n]
%pq_t[$pp_i] := %pq_t[$pq_n]
else
inc($pp_i)
end if
end while
""")
    s.fn("release_all", """
$ra_s := 0
while ($ra_s < 129)
if (%src_n[$ra_s] > 0)
$rs_src := $ra_s
call release_src
end if
%src_sus[$ra_s] := 0
inc($ra_s)
end while
$ra_i := 0
while ($ra_i < $pq_n)
fade_out(%pq_id[$ra_i], $rs_time, 1)
inc($ra_i)
end while
$pq_n := 0
""")
    s.fn("pedal_up", """
$pu_s := 0
while ($pu_s < 128)
if (%src_sus[$pu_s] = 1 and %src_held[$pu_s] = 0)
$rs_src := $pu_s
$rs_time := $rel_us
call release_src
end if
inc($pu_s)
end while
""")
    # controller: pedal, bend, all notes off
    s.cb["controller"] += [
        "if ($CC_NUM = 64 and $use_pedal = 1)",
        "if (%CC[64] >= 64)", "$pedal := 1", "else",
        "if ($pedal = 1)", "$pedal := 0", "call pedal_up", "end if",
        "end if", "end if",
        "if ($CC_NUM = 120 or $CC_NUM = 123)", "$rs_time := 20000", "call release_all", "end if",
    ]
    if melodic:
        s.cb["controller"] += [
            "if ($CC_NUM = $VCC_PITCH_BEND)",
            "$cb_v := (%CC[$VCC_PITCH_BEND] * $pb_range * 100) / 8191 * 1000",
            "change_tune($ALL_EVENTS, $cb_v - $bend, 1)",
            "$bend := $cb_v", "end if",
        ]
    s.cb["listener"] += ["if ($NI_SIGNAL_TYPE = $NI_SIGNAL_TIMER_BEAT)", "inc($tick)",
                         "if ($pq_n > 0)", "call process_pending", "end if"]
    # (listener is closed by finish())
    s.persist.append("call show_page")


def finish(s):
    s.cb["listener"].append("end if")


