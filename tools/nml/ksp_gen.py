# KEYS engine (velocity layers + round robin; EP, guitar, bass, organ, mallets)
# ===========================================================================
def engine_keys(s):
    cfg = s.cfg
    groups = s.inst.groups
    patches = cfg["patches"]
    n = len(patches)
    lo, hi = cfg["range"]
    s.d(f"declare const $NUM_PATCH := {n}", f"declare %pl_n[{n}]", f"declare %pl_split[{n * 4}]",
        f"declare %pl_rrn[{n * 4}]", f"declare %pl_g[{n * 16}]", f"declare %pl_rr[{n * 4}]", f"declare %p_loop[{n}]",
        "declare $kp", "declare $kl", "declare $kr", "declare $kg", "declare $k_db", "declare $kpass", "declare $k_patch",
        "declare polyphonic $p_i", "declare polyphonic $p_cnt", "declare polyphonic $p_vel")
    for i, p in enumerate(patches):
        layers = p["layers"]
        s.d(f"%pl_n[{i}] := {len(layers)}", f"%p_loop[{i}] := {int(p.get('loop', False))}")
        splits = p.get("splits", [])
        for l in range(4):
            sp = splits[l] if l < len(splits) else 127
            s.d(f"%pl_split[{i * 4 + l}] := {sp}")
            rrs = layers[l] if l < len(layers) else []
            s.d(f"%pl_rrn[{i * 4 + l}] := {max(1, len(rrs))}")
            for r in range(4):
                g = groups.index(rrs[r]) if r < len(rrs) else (groups.index(rrs[0]) if rrs else 0)
                s.d(f"%pl_g[{(i * 4 + l) * 4 + r}] := {g}")
    P = PAGE_PLAY
    x = 10
    if n > 1:
        s.label("lbl_patch", P, 10, ROW1 - 2, "Instrument")
        s.ctl(Ctl("patch", "menu", P, 10, ROW1 + 16, items=[p["name"] for p in patches], default=0, width=120,
                  help="Choose the instrument."))
        s.label("lbl_patch2", P, 140, ROW1 - 2, "Layer")
        s.ctl(Ctl("patch2", "menu", P, 140, ROW1 + 16, items=["Off"] + [p["name"] for p in patches], default=0,
                  width=120, help="Layer a second instrument on top."))
        s.ctl(Ctl("mix2", "knob", P, 270, ROW1, "Layer Level", -300, 0, -60, 10, "DB", help="Level of the layer."))
        x = 368
    env_controls(s, x, ROW1, cfg.get("attack", 0), cfg.get("release", 250), 2000, 6000)
    x += 2 * KNOB_DX
    s.ctl(Ctl("vrange", "knob", P, x, ROW1, "Vel Range", 0, 48, cfg.get("vrange", 26), 1, "DB",
              help="Velocity to volume range (0 = no velocity response)."))
    s.ctl(Ctl("vcurve", "knob", P, x + KNOB_DX, ROW1, "Vel Curve", -100, 100, 0, 1, None,
              help="Velocity curve: negative = softer response, positive = harder."))
    ring = cfg.get("let_ring", None)
    if ring is not None:
        s.ctl(Ctl("let_ring", "switch", P, 10, ROW2 + 24, "Let Ring", default=int(ring),
                  help="Notes ring out naturally instead of stopping when you release the key."))
    s.ctl(Ctl("repeat_damp", "knob", P, 108, ROW2, "Re-strike", 10, 500, cfg.get("restrike", 60), 1, "MS",
              help="How fast a still-sounding note fades when the same key is played again.",
              upd=["$retrig_us := $repeat_damp * 1000"]))
    if "rotator" in cfg.get("fx", []):
        s.ctl(Ctl("mw_rot", "switch", P, 206, ROW2 + 24, "Wheel = Fast", default=1,
                  help="Mod wheel above half switches the rotary speaker to fast."))
    vel_db_fn(s)
    s.fn("play_patch", """
$kl := 0
while ($kl < %pl_n[$kp] - 1 and $vc_curved > %pl_split[$kp * 4 + $kl])
inc($kl)
end while
$kr := %pl_rr[$kp * 4 + $kl]
%pl_rr[$kp * 4 + $kl] := ($kr + 1) mod %pl_rrn[$kp * 4 + $kl]
$kg := %grp[%pl_g[($kp * 4 + $kl) * 4 + $kr]]
if ($kg # $NI_NOT_FOUND)
$pv_grp := $kg
$pv_vol := $k_db
call play_voice
end if
""")
    s.fn("start_note", f"""
$nv_n := 0
$vc_in := $sn_vel
call vel_curve
$pv_note := $sn_note
$pv_tune := 0
$pv_pan := 0
$pv_role := 3
$pv_off := $sn_off
$pv_fade := $att_us
if ($sn_fade >= 0)
$pv_fade := $sn_fade
end if
$k_patch := {'$patch' if n > 1 else '0'}
$kp := $k_patch
$k_db := $vc_db + random(-250, 250)
call play_patch
""" + ("""
if ($patch2 > 0)
$kp := $patch2 - 1
$k_db := $vc_db + $mix2 * 100
call play_patch
end if
""" if n > 1 else ""))
    s.cb["note"] += note_head(s) + keys_down_track_note() + poly_note_path(s)
    if ring is not None:
        ring_expr = "$let_ring = 1 and %p_loop[" + ("$patch" if n > 1 else "0") + "] = 0"
    else:
        ring_expr = None
    s.cb["release"] += keys_down_track_release() + poly_release_path(s, ring_expr)
    if "rotator" in cfg.get("fx", []):
        s.cb["controller"] += ["if ($CC_NUM = 1 and $mw_rot = 1)", "if (%CC[1] >= 64)", "$rot_fast := 1", "else",
                               "$rot_fast := 0", "end if", "call upd_rot_fast", "end if"]
    key_colors(s, [(lo, hi, cfg.get("key_color", "$KEY_COLOR_GREEN"))])


