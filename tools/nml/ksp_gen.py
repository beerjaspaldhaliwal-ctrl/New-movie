def ksp_str(s):
    return '"' + s.replace('"', "'") + '"'


class Ctl:
    def __init__(self, var, kind, page, x, y, text="", lo=0, hi=1000, default=0, ratio=1, unit=None,
                 items=None, help="", upd=None, width=None, persist=True, on_ui=None, in_presets=True):
        self.var, self.kind, self.page, self.x, self.y = var, kind, page, x, y
        self.text, self.lo, self.hi, self.default, self.ratio, self.unit = text, lo, hi, default, ratio, unit
        self.items, self.help, self.upd, self.width, self.persist = items, help, upd or [], width, persist
        self.on_ui = on_ui or []          # extra lines run only when the user moves the control
        self.in_presets = in_presets      # included in the "Default" preset reset


class Script:
    def __init__(self, inst):
        self.inst = inst
        self.cfg = inst.cfg
        self.decl = []      # declarations / init code (in order)
        self.post = []      # init code that must come after the UI declarations
        self.funcs = []     # (name, [lines])
        self.ctls = []
        self.persist = []   # extra lines for on persistence_changed (after upd calls)
        self.cb = {"note": [], "release": [], "controller": [], "listener": []}
        self.labels = []
        self.late = []      # functions that call upd_* functions (emitted after them)

    # -- helpers ---------------------------------------------------------
    def d(self, *lines):
        self.decl.extend(lines)

    def fn(self, name, body):
        self.funcs.append((name, [l for l in body.strip("\n").split("\n")]))

    def ctl(self, c):
        self.ctls.append(c)
        return c

    def label(self, var, page, x, y, text, w=96):
        self.labels.append((var, page, x, y, text, w))

    # -- rendering -------------------------------------------------------
    def render(self):
        out = []
        out.append("{ " + f"{LIB_NAME} :: {self.inst.name}" + " }")
        out.append("{ Generated by tools/nml/ksp_gen.py - edit the generator, then rebuild. }")
        out.append("{ Kontakt 7.10+ / Kontakt 8. Vanilla KSP, no compiler needed. }")
        out.append("")
        out.append("on init")
        body = list(self.decl)
        nui = len(self.ctls) + len(self.labels)
        body += [f"declare const $NUM_UI := {nui}", f"declare %ui_id[{nui}]", f"declare %ui_page[{nui}]"]
        k = 0
        for (var, page, x, y, text, w) in self.labels:
            body += [f"declare ui_label ${var} (1, 1)",
                     f"set_text(${var}, {ksp_str(text)})",
                     f"set_control_par(get_ui_id(${var}), $CONTROL_PAR_WIDTH, {w})",
                     f"move_control_px(${var}, {x}, {y})",
                     f"%ui_id[{k}] := get_ui_id(${var})", f"%ui_page[{k}] := {page}"]
            k += 1
        for c in self.ctls:
            v = "$" + c.var
            if c.kind == "knob":
                body.append(f"declare ui_knob {v} ({c.lo}, {c.hi}, {c.ratio})")
                body.append(f"set_text({v}, {ksp_str(c.text)})")
                if c.unit:
                    body.append(f"set_knob_unit({v}, $KNOB_UNIT_{c.unit})")
                body.append(f"set_knob_defval({v}, {c.default})")
            elif c.kind == "menu":
                body.append(f"declare ui_menu {v}")
                for i, it in enumerate(c.items):
                    body.append(f"add_menu_item({v}, {ksp_str(it)}, {i})")
                body.append(f"set_control_par(get_ui_id({v}), $CONTROL_PAR_WIDTH, {c.width or 120})")
            elif c.kind == "switch":
                body.append(f"declare ui_switch {v}")
                body.append(f"set_text({v}, {ksp_str(c.text)})")
                body.append(f"set_control_par(get_ui_id({v}), $CONTROL_PAR_WIDTH, {c.width or 88})")
            elif c.kind == "value":
                body.append(f"declare ui_value_edit {v} ({c.lo}, {c.hi}, {c.ratio})")
                body.append(f"set_text({v}, {ksp_str(c.text)})")
                body.append(f"set_control_par(get_ui_id({v}), $CONTROL_PAR_WIDTH, {c.width or 96})")
            else:
                raise ValueError(c.kind)
            body.append(f"{v} := {c.default}")
            if c.help:
                body.append(f"set_control_help({v}, {ksp_str(c.help[:300])})")
            body.append(f"move_control_px({v}, {c.x}, {c.y})")
            if c.persist:
                body.append(f"make_persistent({v})")
            body += [f"%ui_id[{k}] := get_ui_id({v})", f"%ui_page[{k}] := {c.page}"]
            k += 1
        body += self.post
        out += ["  " + l for l in body]
        out.append("end on")
        out.append("")
        for name, lines in self.funcs:
            out.append(f"function {name}")
            out += ["  " + l for l in lines]
            out.append("end function")
            out.append("")
        for c in self.ctls:
            out.append(f"function upd_{c.var}")
            out += ["  " + l for l in (c.upd or ["{ no side effects }"])]
            out.append("end function")
            out.append("")
        for name, lines in self.late:
            out.append(f"function {name}")
            out += ["  " + l for l in lines]
            out.append("end function")
            out.append("")
        out.append("on persistence_changed")
        for c in self.ctls:
            out.append(f"  call upd_{c.var}")
        out += ["  " + l for l in self.persist]
        out.append("end on")
        out.append("")
        for cbn in ("note", "release", "controller", "listener"):
            if self.cb[cbn]:
                out.append(f"on {cbn}")
                out += ["  " + l for l in self.cb[cbn]]
                out.append("end on")
                out.append("")
        for c in self.ctls:
            out.append(f"on ui_control (${c.var})")
            out.append(f"  call upd_{c.var}")
            out += ["  " + l for l in c.on_ui]
            out.append("end on")
            out.append("")
        return "\n".join(_indent(out)) + "\n"


def _indent(lines):
    """Re-indent bodies of if/while/select blocks for readability."""
    res = []
    depth = 0
    for raw in lines:
        st = raw.strip()
        if not st:
            res.append("")
            continue
        if st.startswith(("on ", "function ")):
            res.append(st)
            depth = 1
            continue
        if st in ("end on", "end function"):
            res.append(st)
            depth = 0
            continue
        if st.startswith(("end if", "end while")):
            depth -= 1
        elif st.startswith("end select"):
            depth -= 2
        if st == "else" or st.startswith("case "):
            res.append("  " * (depth - 1) + st)
        else:
            res.append("  " * depth + st)
        if st.startswith(("if ", "if(", "while ", "while(")):
            depth += 1
        elif st.startswith(("select ", "select(")):
            depth += 2
    return res


